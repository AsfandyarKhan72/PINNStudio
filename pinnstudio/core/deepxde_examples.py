def build_config(example, ref_root, keep=None):
    """A PINNConfig for `example`: PINNConfig defaults, then the example's
    settings, with "@REF/" paths resolved against `ref_root`. `keep` is an
    optional dict of the user's own preferences carried over unchanged
    (save directory, GPU, plot styling, ...)."""
    cfg = PINNConfig()
    base = dict(optimizer_scheduler=False, adapt_method="None", ea_files="[]", custom_bc_json="[]",
                loss_weights_multi="", inverse_variables_json="", inverse_obs_files_json="",
                problem_type="Forward", template_type="",
                plot_colormap="jet")   # same as PINNStudio's own templates
    settings = {**base, **example.settings}

    def _resolve(v):
        if isinstance(v, str) and "@REF/" in v:
            return v.replace("@REF/", ref_root.rstrip("/\\") + os.sep)
        return v

    for k, v in settings.items():
        if not hasattr(cfg, k):
            raise KeyError(f"{example.name}: unknown setting {k!r}")
        setattr(cfg, k, _resolve(v))
    n_out = int(cfg.num_outputs or 1)
    if "layers" in settings and len(cfg.layers) >= 2:
        n_in = 1 + (1 if cfg.problem_dim in ("2D", "3D") else 0) + (1 if cfg.problem_dim == "3D" else 0) \
            + (0 if cfg.steady_state else 1)
        cfg.layers = [n_in] + list(cfg.layers[1:-1]) + [n_out]
    cfg.pde_expression = (cfg.pde_expressions or "").split("|")[0]
    if "ic_expressions" in settings:
        cfg.ic_expression = (cfg.ic_expressions or "").split("|")[0]
    if "ic_active" not in settings:
        cfg.ic_active = ",".join(["True"] * n_out)
    if "num_outputs" in settings and "output_names" not in settings:
        cfg.output_names = ",".join(["u", "v", "w", "p"][:n_out])
    if "loss_weights_multi" not in example.settings:
        # DeepXDE weighs every loss term 1 unless a script says otherwise;
        # PINNStudio's own default puts 100 on initial conditions.
        n_eq = int(cfg.num_equations or 0) or n_out
        n_bc = len(json.loads(cfg.custom_bc_json or "[]"))
        n_ic = 0 if cfg.steady_state else sum(
            s.strip() == "True" for s in (cfg.ic_active or "").split(",")[:n_out])
        cfg.loss_weights_multi = ",".join(["1"] * (n_eq + n_bc + n_ic))
    for k, v in (keep or {}).items():
        if k not in example.settings:
            setattr(cfg, k, v)
    return cfg

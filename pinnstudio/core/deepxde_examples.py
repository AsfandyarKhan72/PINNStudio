"""DeepXDE's own PINN examples as PINNStudio Quick Examples.

Each entry reproduces one script from DeepXDE's documentation
(https://deepxde.readthedocs.io/en/latest/demos/pinn_forward.html and
.../pinn_inverse.html) as PINNStudio settings: the same equation, geometry,
boundary/initial conditions, network, optimizers, iteration counts and
loss weights, so loading it and pressing Solve trains what the DeepXDE
script trains. Where a problem has an exact solution, Error Analysis is set
up to compare against it ("Reference from formula"); where DeepXDE compares
against a dataset, the matching reference files under reference_data/ are
used (PINNStudio's own, or generated by tools/make_deepxde_reference_data.py
-- nothing is copied from DeepXDE's repository).

`settings` holds PINNConfig fields. Paths starting with "@REF/" are
resolved against the reference_data directory by build_config(). Any
deviation from the DeepXDE script is stated in `note`.
"""

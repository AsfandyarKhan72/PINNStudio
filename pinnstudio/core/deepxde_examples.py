@dataclasses.dataclass(frozen=True)
class Example:
    name: str            # menu text (shortened DeepXDE title)
    category: str        # FORWARD or INVERSE
    source: str          # DeepXDE page / script
    settings: dict       # PINNConfig fields
    note: str = ""       # anything that differs from the DeepXDE script
    # Optional Inverse-mode version (PINNStudio's addition; DeepXDE's script
    # is forward only): settings applied on top of `settings` when the
    # example is picked from the Inverse list, and its note.
    inverse: dict = None
    inverse_note: str = ""


def _bc(type_, location="True", value="0", component=0, **extra):
    d = {"type": type_, "location": location, "value": value, "component": component}
    d.update(extra)
    return d


def _bcs(*rows):
    return json.dumps(list(rows))


def _net(layers, init="Glorot uniform", activation="tanh", network_type="FNN"):
    return dict(layers=list(layers), kernel_initializer=init, activation=activation, network_type=network_type)


def _adam(iterations, lr=1e-3):
    return dict(optimizer="adam", learning_rate=lr, iterations=iterations)


def _steady_1d(a, b):
    return dict(problem_dim="1D", steady_state=True, geometry_type="Interval", x_min=float(a), x_max=float(b),
                num_initial=0)


def _time_1d(a, b, t0, t1):
    return dict(problem_dim="1D", steady_state=False, geometry_type="Interval", x_min=float(a), x_max=float(b),
                t_min=float(t0), t_max=float(t1))


def _ode(t0, t1):
    """ODE problem (Round 74): only t, in [t0, t1]."""
    return dict(problem_dim="ODE", steady_state=False, geometry_type="Interval", t_min=float(t0), t_max=float(t1),
                num_initial=0)


def _formula_ref(formulas, times=""):
    return dict(ea_ref_mode="formula", ea_ref_formula="|".join(formulas), ea_ref_times=times,
                ea_do_line=True, ea_do_surface=True)


def _scheduler(*phases):
    return dict(optimizer_scheduler=True, scheduler_same_weights=True, scheduler_phases=json.dumps(list(phases)))


def _phase(optimizer, iterations, lr=1e-3, decay=None):
    p = {"optimizer": optimizer, "iterations": iterations, "lr": lr, "decay_type": "none"}
    if decay:
        p["decay_type"], p["decay_p1"], p["decay_p2"] = decay
    return p


def _consts(*pairs):
    """Named constants (Round 70), as DeepXDE's scripts define them at the top."""
    return dict(constants=json.dumps([{"name": n, "value": v} for n, v in pairs]))


def _ex(name, category, source, *parts, note="", inverse=None, inverse_note=""):
    s = {}
    for p in parts:
        s.update(p)
    return Example(name, category, source, s, note, inverse, inverse_note)



"""Where each documented feature is in the code: the one list the documentation's source-code links come from.

Each feature has an id (the snippet website/_snippets/source/<id>.md that `tools/docs/make_source_links.py`
writes from it), a title, the site pages that describe it (`pages`, relative to website/) and a list of
entries:

    path    a file in the repository, relative to its root
    symbol  optional: a function, class or assignment in that file, dotted for a method or a nested name
            (`MainWindow._build_config`, `generate_clean_script._result_plot_parts`, `PINNConfig.validate`);
            for a file that is not Python, a text the file must contain
    role    "entry point" (where the feature starts: the GUI panel, the generator function), "helper"
            (code it relies on) or "test" (the regression tests that exercise it most directly)
    note    a few words on what the entry does

Links name the file and the function, never line numbers (the base reference, `extra.source_ref` in mkdocs.yml,
is a branch until a release tag exists). After changing this file or renaming code it names, run

    python tools/docs/make_source_links.py          # rewrite the snippets
    python tools/docs/make_source_links.py --check  # what CI runs: names exist, snippets up to date
"""


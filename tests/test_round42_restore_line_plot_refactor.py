"""
Round 42 -- codebase cleanup, phase 5 (audit §2e, first sub-round): the
"Line (time steps)" and "Animation Line (GIF)" branches of
main_window.py's two restore script builders (_build_restore_script,
_build_restore_script_ta) were two independently hand-typed copies each,
~90% textually identical (confirmed via difflib before this round) and
differing only in (a) whether a steady-state restore is even possible
(only the single-model path supports it) and (b) which model object
.predict() is called on for a given time value (a fixed `model` vs. a
per-time-value Time-Adaptive step model). Both pairs are now generated by
one shared codegen.py helper each (_restore_line_plot_code /
_restore_line_animation_code), parameterized by a single is_time_adaptive
flag.

Before this round's patch was built, the refactor was verified to render
BYTE-FOR-BYTE IDENTICAL output to the original hand-typed branches across
50 generated-script variants (1D/2D/3D x steady/transient x default and
custom viz settings x both viz types, for both the single-model and
Time-Adaptive builders) by diffing the patched repo's output against a
fresh clone of the pre-patch tip -- see the round's delivery notes for
that comparison; it isn't repeated here since it needs two separate
repo checkouts, not something a single pytest run can do. What THIS file
checks is that the shared helpers still produce real, runnable scripts
end to end -- actual restore of a real trained+saved checkpoint, for
both viz types, both builders, including geometry masking on a
non-rectangular domain (so the extraction didn't quietly break masking
for either caller) and, for the Time-Adaptive builder, that per-step
model routing still restores and picks the correct step.

Run directly:
    QT_QPA_PLATFORM=offscreen python3 tests/test_round42_restore_line_plot_refactor.py
"""

_app = QApplication.instance() or QApplication(sys.argv)

from pinnstudio.ui.main_window import MainWindow


def _base_cfg(layers, problem_dim, steady, **geom_fields):
    cfg = {
        "layers": layers, "activation": "tanh",
        "x_min": 0.0, "x_max": 1.0, "y_min": 0.0, "y_max": 1.0,
        "z_min": 0.0, "z_max": 1.0, "t_min": 0.0, "t_max": 1.0,
        "problem_dim": problem_dim, "steady_state": steady, "loss_type": "MSE",
        "output_names": "u", "geometry_type": "Rectangle",
    }
    cfg.update(geom_fields)
    return cfg


class _DTypeSafeGeomForTraining:
    """Same dtype workaround test_restore_geometry_masking.py already
    uses for its own training step on a non-Rectangle geometry."""
    def __init__(self, geom):
        self._geom = geom
    def __getattr__(self, name):
        return getattr(self._geom, name)
    def random_points(self, n, random="pseudo"):
        import deepxde as dde, numpy as np
        return self._geom.random_points(n, random=random).astype(dde.config.real(np))
    def uniform_points(self, n, boundary=True):
        import deepxde as dde, numpy as np
        return self._geom.uniform_points(n, boundary=boundary).astype(dde.config.real(np))
    def random_boundary_points(self, n, random="pseudo"):
        import deepxde as dde, numpy as np
        return self._geom.random_boundary_points(n, random=random).astype(dde.config.real(np))
    def uniform_boundary_points(self, n):
        import deepxde as dde, numpy as np
        return self._geom.uniform_boundary_points(n).astype(dde.config.real(np))


def _train_and_save_model(tmpdir, dde_geom, steady, t0, t1, layers, tag):
    import deepxde as dde

    dde_geom = _DTypeSafeGeomForTraining(dde_geom)
    if steady:
        data = dde.data.PDE(dde_geom, lambda x, y: y[:, 0:1] * 0, [], num_domain=40, num_test=40)
    else:
        timedomain = dde.geometry.TimeDomain(t0, t1)
        geomtime = dde.geometry.GeometryXTime(dde_geom, timedomain)
        data = dde.data.TimePDE(geomtime, lambda x, y: y[:, 0:1] * 0, [], num_domain=40,
                                 num_test=40, num_initial=5)

    net = dde.nn.FNN(layers, "tanh", "Glorot uniform")
    model = dde.Model(data, net)
    model.compile("adam", lr=0.001)
    model.train(iterations=1, display_every=1000)
    return model.save(os.path.join(tmpdir, tag))


def _run_script(script, tmpdir, tag, timeout_s=150):
    sp = os.path.join(tmpdir, f"{tag}_script.py")
    with open(sp, "w", encoding="utf-8") as f:
        f.write(script)
    return subprocess.run([sys.executable, sp], cwd=tmpdir, capture_output=True, text=True, timeout=timeout_s)


def run():
    failures = []

    def check(cond, msg):
        if not cond:
            failures.append(msg)

    try:
        import deepxde as _dde_probe  # noqa: F401
        import torch as _torch_probe  # noqa: F401
    except ImportError:
        print("SKIPPED: deepxde/torch not installed in this environment.")
        return failures

    import deepxde as dde

    win = MainWindow()
    win._restore_viz_settings = dict(win._restore_viz_settings or {})
    win._restore_viz_settings["resolution"] = 24
    win._restore_viz_settings["line_steps"] = 4
    win._restore_viz_settings["n_steps"] = 4

    # ── single-model restore: "Line (time steps)" on a Disk (2D, transient),
    # masked line slice at the midpoint should drop some out-of-domain
    # x-samples -- proves _restore_line_plot_code's geometry-masking
    # output is still wired correctly after the extraction.
    with tempfile.TemporaryDirectory() as tmpdir:
        disk_geom = dde.geometry.Disk([0.5, 0.5], 0.4)
        layers = [3, 16, 16, 1]
        model_path = _train_and_save_model(tmpdir, disk_geom, False, 0.0, 1.0, layers, "disk_line")
        cfg = _base_cfg(layers, "2D", False, geometry_type="Disk",
                         geom_center_x=0.5, geom_center_y=0.5, geom_radius=0.4)
        script = win._build_restore_script(model_path, cfg, "adam", "Line (time steps)", 0, 4, tmpdir)
        check("geom.inside(" in script, "single-model Line (time steps) script should mask with geom.inside")
        proc = _run_script(script, tmpdir, "disk_line")
        check(proc.returncode == 0,
              f"single-model Disk Line (time steps) restore should run cleanly, got {proc.returncode}:\n"
              f"{proc.stdout}\n{proc.stderr}")
        check("RESTORE_DONE" in proc.stdout, "single-model Disk Line restore should finish (RESTORE_DONE)")
        check(os.path.exists(os.path.join(tmpdir, "restored_plot.png")),
              "single-model Disk Line restore should save restored_plot.png")

    # ── single-model restore: "Animation Line (GIF)" on a steady 1D
    # problem -- the is_steady-capable branch (only the single-model path
    # ever takes it).
    with tempfile.TemporaryDirectory() as tmpdir:
        interval_geom = dde.geometry.Interval(0.0, 1.0)
        layers = [1, 16, 16, 1]
        model_path = _train_and_save_model(tmpdir, interval_geom, True, 0.0, 1.0, layers, "steady_anim")
        cfg = _base_cfg(layers, "1D", True)
        script = win._build_restore_script(model_path, cfg, "adam", "Animation Line (GIF)", 0, 4, tmpdir)
        check('"steady-state" if is_steady' not in script,
              "Animation Line (GIF) never had the is_steady _line_label branch -- only the static "
              "Line plot does; this is a sanity check that the two helpers weren't accidentally swapped")
        proc = _run_script(script, tmpdir, "steady_anim", timeout_s=180)
        check(proc.returncode == 0,
              f"single-model steady-state Animation Line (GIF) restore should run cleanly, got "
              f"{proc.returncode}:\n{proc.stdout}\n{proc.stderr}")
        check("RESTORE_DONE" in proc.stdout, "steady-state Animation Line restore should finish")
        check(os.path.exists(os.path.join(tmpdir, "restored_animation.gif")),
              "steady-state Animation Line restore should save restored_animation.gif")

    # ── Time-Adaptive restore: "Line (time steps)" + "Animation Line
    # (GIF)" on a Disk (2D), 2 steps -- confirms per-step model routing
    # (_ta_model_for_t) and geometry masking both still work through the
    # shared helper's is_time_adaptive=True path.
    with tempfile.TemporaryDirectory() as tmpdir:
        disk_geom = dde.geometry.Disk([0.5, 0.5], 0.4)
        layers = [3, 16, 16, 1]
        step0_path = _train_and_save_model(tmpdir, disk_geom, False, 0.0, 0.5, layers, "ta_step0")
        step1_path = _train_and_save_model(tmpdir, disk_geom, False, 0.5, 1.0, layers, "ta_step1")
        ta_steps = [
            {"t0": 0.0, "t1": 0.5, "model_path": step0_path,
             "cfg": {"layers": layers, "activation": "tanh", "loss_type": "MSE", "is_lbfgs": False}},
            {"t0": 0.5, "t1": 1.0, "model_path": step1_path,
             "cfg": {"layers": layers, "activation": "tanh", "loss_type": "MSE", "is_lbfgs": False}},
        ]
        cfg = {"layers": layers, "activation": "tanh", "x_min": 0.0, "x_max": 1.0,
               "y_min": 0.0, "y_max": 1.0, "problem_dim": "2D", "output_names": "u",
               "geometry_type": "Disk", "geom_center_x": 0.5, "geom_center_y": 0.5, "geom_radius": 0.4}

        line_script = win._build_restore_script_ta(ta_steps, cfg, "adam", "Line (time steps)", 0, 4, tmpdir)
        check("geom.inside(" in line_script, "TA Line (time steps) script should still mask with geom.inside")
        check("_ta_model_for_t" in line_script, "TA Line (time steps) script should route through _ta_model_for_t")
        proc = _run_script(line_script, tmpdir, "ta_disk_line")
        check(proc.returncode == 0,
              f"TA Disk Line (time steps) restore should run cleanly, got {proc.returncode}:\n"
              f"{proc.stdout}\n{proc.stderr}")
        check("RESTORE_DONE" in proc.stdout, "TA Disk Line restore should finish")
        check("Restored step 1/2" in proc.stdout and "Restored step 2/2" in proc.stdout,
              "TA Disk Line restore should restore BOTH step models (one of them is reached because "
              "t_steps_vals spans the full [0, 1] combined range)")
        check(os.path.exists(os.path.join(tmpdir, "restored_plot.png")),
              "TA Disk Line restore should save restored_plot.png")

        anim_script = win._build_restore_script_ta(ta_steps, cfg, "adam", "Animation Line (GIF)", 0, 4, tmpdir)
        proc2 = _run_script(anim_script, tmpdir, "ta_disk_anim", timeout_s=180)
        check(proc2.returncode == 0,
              f"TA Disk Animation Line (GIF) restore should run cleanly, got {proc2.returncode}:\n"
              f"{proc2.stdout}\n{proc2.stderr}")
        check("RESTORE_DONE" in proc2.stdout, "TA Disk Animation Line restore should finish")
        check(os.path.exists(os.path.join(tmpdir, "restored_animation.gif")),
              "TA Disk Animation Line restore should save restored_animation.gif")

    return failures


def main():
    failures = run()
    for f in failures:
        print("FAIL:", f)
    if failures:
        print(f"\n{len(failures)} FAILURE(S)")
        return 1
    print("\nALL ROUND 42 RESTORE LINE-PLOT REFACTOR TESTS PASSED")
    return 0


def test_round42_restore_line_plot_refactor():
    failures = run()
    assert not failures, "\n".join(failures)


if __name__ == "__main__":
    sys.exit(main())

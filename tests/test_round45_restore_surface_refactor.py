#!/usr/bin/env python3
"""
Round 45 -- codebase cleanup, phase 8 (audit §2e, sub-round 3): the static
"Surface" branches of main_window.py's two restore script builders
(_build_restore_script, _build_restore_script_ta) were two hand-typed
copies. Round 43 measured them at only ~47% similar and left them alone,
partly because the Time-Adaptive copy didn't mask to the real geometry.
Round 44 fixed that masking gap, and after it the two copies differ only
in things that follow from one is_time_adaptive flag: the bbox source for
the 3D face grid, per-panel step-model routing (_ta_model_for_t), the
steady-state branches (single-model only -- a Time-Adaptive run is never
steady), and 1D batched vs. per-row prediction. Both are now generated by
one shared codegen.py helper, _restore_surface_code, same approach as
Round 42 (Line/Animation-Line) and Round 43 (Animation Surface).

Before the commit, the refactor was checked to render BYTE-FOR-BYTE
IDENTICAL scripts to the original hand-typed branches across 300
randomized builder/dimension/steady/settings combinations (all 9
reachable builder x dim x steady combos covered); that comparison needs a
pre-refactor checkout and isn't repeated here. What THIS file checks is
that the shared helper still produces real, runnable scripts end to end:
an actual restore of a real trained+saved checkpoint for every branch of
the helper (1D transient, 1D steady, 2D steady, 2D transient, 3D
transient on the single-model side; 1D, 2D and 3D on the Time-Adaptive
side), plus a side-channel mask dump on a Disk to confirm both sides
still mask to the real geometry (Round 44's fix) through the helper.

Run directly:
    QT_QPA_PLATFORM=offscreen python3 tests/test_round45_restore_surface_refactor.py
"""
import os
import subprocess
import sys
import tempfile

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ.setdefault("DDE_BACKEND", "pytorch")

_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _REPO_ROOT not in sys.path:
    sys.path.insert(0, _REPO_ROOT)

from PyQt6.QtWidgets import QApplication

_app = QApplication.instance() or QApplication(sys.argv)

from pinnstudio.ui.main_window import MainWindow


def _base_cfg(layers, problem_dim, steady, **geom_fields):
    cfg = {
        "layers": layers, "activation": "tanh",
        "x_min": 0.0, "x_max": 1.0, "y_min": 0.0, "y_max": 1.0,
        "z_min": 0.0, "z_max": 1.0, "t_min": 0.0, "t_max": 1.0,
        "problem_dim": problem_dim, "steady_state": steady, "loss_type": "MSE",
        "output_names": "u", "geometry_type": "Rectangle",
    }
    cfg.update(geom_fields)
    return cfg


def _train_and_save_model(tmpdir, dde_geom, t0, t1, layers, tag, steady=False):
    import deepxde as dde

    if steady:
        data = dde.data.PDE(dde_geom, lambda x, y: y[:, 0:1] * 0, [], num_domain=40, num_test=40)
    else:
        geomtime = dde.geometry.GeometryXTime(dde_geom, dde.geometry.TimeDomain(t0, t1))
        data = dde.data.TimePDE(geomtime, lambda x, y: y[:, 0:1] * 0, [], num_domain=40,
                                 num_test=40, num_initial=5)
    net = dde.nn.FNN(layers, "tanh", "Glorot uniform")
    model = dde.Model(data, net)
    model.compile("adam", lr=0.001)
    model.train(iterations=1, display_every=1000)
    return model.save(os.path.join(tmpdir, tag))


def _ta_steps(tmpdir, dde_geom, layers):
    steps = []
    for i, (t0, t1) in enumerate([(0.0, 0.5), (0.5, 1.0)]):
        path = _train_and_save_model(tmpdir, dde_geom, t0, t1, layers, f"ta_step{i}")
        steps.append({"t0": t0, "t1": t1, "model_path": path,
                      "cfg": {"layers": layers, "activation": "tanh", "loss_type": "MSE"}})
    return steps


def _run_script(script, tmpdir, tag, timeout_s=240):
    sp = os.path.join(tmpdir, f"{tag}_script.py")
    with open(sp, "w", encoding="utf-8") as f:
        f.write(script)
    return subprocess.run([sys.executable, sp], cwd=tmpdir, capture_output=True, text=True, timeout=timeout_s)


def run():
    failures = []

    def check(cond, msg):
        if not cond:
            failures.append(msg)

    try:
        import deepxde as _dde_probe  # noqa: F401
        import torch as _torch_probe  # noqa: F401
    except ImportError:
        print("SKIPPED: deepxde/torch not installed in this environment.")
        return failures

    import numpy as np
    import deepxde as dde

    win = MainWindow()
    win._restore_viz_settings = dict(win._restore_viz_settings or {})
    win._restore_viz_settings["resolution"] = 24
    win._restore_viz_settings["n_2d_snapshots"] = 2

    def expect_ok(proc, label, tmpdir):
        check(proc.returncode == 0,
              f"{label} should run cleanly, got {proc.returncode}:\n{proc.stdout}\n{proc.stderr}")
        check("RESTORE_DONE" in proc.stdout, f"{label} should finish (RESTORE_DONE)")
        check(os.path.exists(os.path.join(tmpdir, "restored_plot.png")),
              f"{label} should save restored_plot.png")

    # ── single-model side ───────────────────────────────────────────────
    single_cases = [
        # (tag, dim, steady, geometry, layers, extra cfg)
        ("single_1d", "1D", False, dde.geometry.Interval(0.0, 1.0), [2, 16, 1], {}),
        ("single_1d_steady", "1D", True, dde.geometry.Interval(0.0, 1.0), [1, 16, 1], {}),
        ("single_2d_steady_disk", "2D", True, dde.geometry.Disk([0.5, 0.5], 0.5), [2, 16, 1],
         {"geometry_type": "Disk", "geom_center_x": 0.5, "geom_center_y": 0.5, "geom_radius": 0.5}),
        ("single_2d_disk", "2D", False, dde.geometry.Disk([0.5, 0.5], 0.5), [3, 16, 1],
         {"geometry_type": "Disk", "geom_center_x": 0.5, "geom_center_y": 0.5, "geom_radius": 0.5}),
        ("single_3d", "3D", False, dde.geometry.Cuboid([0.0, 0.0, 0.0], [1.0, 1.0, 1.0]), [4, 16, 1],
         {"geometry_type": "Cuboid"}),
    ]
    for tag, dim, steady, geom, layers, extra in single_cases:
        with tempfile.TemporaryDirectory() as tmpdir:
            model_path = _train_and_save_model(tmpdir, geom, 0.0, 1.0, layers, tag, steady=steady)
            cfg = _base_cfg(layers, dim, steady, **extra)
            script = win._build_restore_script(model_path, cfg, "adam", "Surface", 0, 3, tmpdir)
            check("_ta_model_for_t" not in script, f"{tag}: single-model Surface must not route per-step models")
            check("geom.bbox" in script, f"{tag}: single-model Surface should read the 3D bbox off geom")
            mask_path = os.path.join(tmpdir, "mask.npy")
            if dim == "2D":
                script += f"\nnp.save({mask_path!r}, _inside2d)\n"
            proc = _run_script(script, tmpdir, tag)
            expect_ok(proc, f"single-model {tag} Surface restore", tmpdir)
            if dim == "2D":
                check(os.path.exists(mask_path), f"{tag}: mask dump should have been written")
            if dim == "2D" and os.path.exists(mask_path):
                m = np.load(mask_path)
                check(bool(m.any()) and bool((~m).any()),
                      f"{tag}: Disk mask should be genuinely mixed (inside and outside points)")

    # ── Time-Adaptive side ──────────────────────────────────────────────
    ta_cases = [
        ("ta_1d", "1D", dde.geometry.Interval(0.0, 1.0), [2, 16, 1], {}),
        ("ta_2d_disk", "2D", dde.geometry.Disk([0.5, 0.5], 0.5), [3, 16, 1],
         {"geometry_type": "Disk", "geom_center_x": 0.5, "geom_center_y": 0.5, "geom_radius": 0.5}),
        ("ta_3d", "3D", dde.geometry.Cuboid([0.0, 0.0, 0.0], [1.0, 1.0, 1.0]), [4, 16, 1],
         {"geometry_type": "Cuboid"}),
    ]
    for tag, dim, geom, layers, extra in ta_cases:
        with tempfile.TemporaryDirectory() as tmpdir:
            steps = _ta_steps(tmpdir, geom, layers)
            cfg = _base_cfg(layers, dim, False, **extra)
            script = win._build_restore_script_ta(steps, cfg, "adam", "Surface", 0, 3, tmpdir)
            check("_ta_model_for_t" in script, f"{tag}: TA Surface should route through _ta_model_for_t")
            check("_ta_build_geomtime(" in script and ".geometry.bbox" in script,
                  f"{tag}: TA Surface should source its 3D bbox from _ta_build_geomtime")
            mask_path = os.path.join(tmpdir, "mask.npy")
            if dim == "2D":
                script += f"\nnp.save({mask_path!r}, _inside2d)\n"
            proc = _run_script(script, tmpdir, tag)
            expect_ok(proc, f"TA {tag} Surface restore", tmpdir)
            check("Restored step 1/2" in proc.stdout and "Restored step 2/2" in proc.stdout,
                  f"{tag}: TA Surface restore should restore BOTH step models")
            if dim == "2D":
                check(os.path.exists(mask_path), f"{tag}: mask dump should have been written")
            if dim == "2D" and os.path.exists(mask_path):
                m = np.load(mask_path)
                check(bool(m.any()) and bool((~m).any()),
                      f"{tag}: Disk mask should be genuinely mixed (inside and outside points)")

    return failures


def main():
    failures = run()
    for f in failures:
        print("FAIL:", f)
    if failures:
        print(f"\n{len(failures)} FAILURE(S)")
        return 1
    print("\nALL ROUND 45 RESTORE SURFACE REFACTOR TESTS PASSED")
    return 0


def test_round45_restore_surface_refactor():
    failures = run()
    assert not failures, "\n".join(failures)


if __name__ == "__main__":
    sys.exit(main())

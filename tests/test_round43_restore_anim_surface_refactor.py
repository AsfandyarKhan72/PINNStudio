#!/usr/bin/env python3
"""
Round 43 -- codebase cleanup, phase 6 (audit §2e, sub-round 2): the
"Animation Surface (GIF)" branches of main_window.py's two restore
script builders (_build_restore_script, _build_restore_script_ta) were
two independently hand-typed copies, ~82% textually identical (confirmed
via difflib before this round -- the biggest matching blocks were 30/25/
16/12 lines) and differing only in things that follow from one
is_time_adaptive flag: which bbox source feeds the 3D face grid
(geom.bbox vs. a geomtime helper's own bbox, resolved once at the start
rather than per frame), whether each frame needs its own Time-Adaptive
model resolved before predicting (and the extra model argument that goes
with it), the is_steady-only-possible-on-the-single-model-path defensive
branches, and (1D case only) whether a frame is predicted as one batched
80x80 grid (single model, cheap to over-predict once) or as one row's
worth of 80 points per frame then tiled down (Time-Adaptive, where
re-resolving the model AND re-predicting 80x more points than needed per
frame would be wasteful). Both pairs are now generated by one shared
codegen.py helper, _restore_anim_surface_code, parameterized by a single
is_time_adaptive flag -- same approach as Round 42's Line/Animation-Line
pair.

(The static "Surface" branch of the same two builders was measured in
the same round and found to be only ~47% similar with small scattered
matches -- genuinely different code, including an apparent real gap
where the Time-Adaptive Surface branch never masks to the real geometry
at all while the single-model Surface branch does -- so it was
deliberately NOT touched here; see this round's delivery notes. Also
noted but not fixed: NEITHER Animation Surface (GIF) branch, before or
after this refactor, masks to the real geometry -- unlike the static
Surface branches, that gap is symmetric between the two builders, so
this refactor doesn't change that behavior either way.)

Before this round's patch was built, the refactor was verified to render
BYTE-FOR-BYTE IDENTICAL output to the original hand-typed branches
across a 300-trial randomized fuzz check (varying every substituted
value) -- see the round's delivery notes for that comparison; it isn't
repeated here. What THIS file checks is that the shared helper still
produces real, runnable scripts end to end -- actual restore of a real
trained+saved checkpoint, for both dimensions the two builders structurally
diverge on (2D and 3D), both builders, confirming per-step model routing
for the Time-Adaptive side.

Run directly:
    QT_QPA_PLATFORM=offscreen python3 tests/test_round43_restore_anim_surface_refactor.py
"""
import os
import subprocess
import sys
import tempfile

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ.setdefault("DDE_BACKEND", "pytorch")

_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _REPO_ROOT not in sys.path:
    sys.path.insert(0, _REPO_ROOT)

from PyQt6.QtWidgets import QApplication

_app = QApplication.instance() or QApplication(sys.argv)

from pinnstudio.ui.main_window import MainWindow


def _base_cfg(layers, problem_dim, steady, **geom_fields):
    cfg = {
        "layers": layers, "activation": "tanh",
        "x_min": 0.0, "x_max": 1.0, "y_min": 0.0, "y_max": 1.0,
        "z_min": 0.0, "z_max": 1.0, "t_min": 0.0, "t_max": 1.0,
        "problem_dim": problem_dim, "steady_state": steady, "loss_type": "MSE",
        "output_names": "u", "geometry_type": "Rectangle",
    }
    cfg.update(geom_fields)
    return cfg


def _train_and_save_model(tmpdir, dde_geom, t0, t1, layers, tag):
    import deepxde as dde

    timedomain = dde.geometry.TimeDomain(t0, t1)
    geomtime = dde.geometry.GeometryXTime(dde_geom, timedomain)
    data = dde.data.TimePDE(geomtime, lambda x, y: y[:, 0:1] * 0, [], num_domain=40,
                             num_test=40, num_initial=5)

    net = dde.nn.FNN(layers, "tanh", "Glorot uniform")
    model = dde.Model(data, net)
    model.compile("adam", lr=0.001)
    model.train(iterations=1, display_every=1000)
    return model.save(os.path.join(tmpdir, tag))


def _run_script(script, tmpdir, tag, timeout_s=240):
    sp = os.path.join(tmpdir, f"{tag}_script.py")
    with open(sp, "w", encoding="utf-8") as f:
        f.write(script)
    return subprocess.run([sys.executable, sp], cwd=tmpdir, capture_output=True, text=True, timeout=timeout_s)


def run():
    failures = []

    def check(cond, msg):
        if not cond:
            failures.append(msg)

    try:
        import deepxde as _dde_probe  # noqa: F401
        import torch as _torch_probe  # noqa: F401
    except ImportError:
        print("SKIPPED: deepxde/torch not installed in this environment.")
        return failures

    import deepxde as dde

    win = MainWindow()
    win._restore_viz_settings = dict(win._restore_viz_settings or {})
    win._restore_viz_settings["resolution"] = 16
    win._restore_viz_settings["n_2d_snapshots"] = 2
    win._restore_viz_settings["n_steps"] = 3

    # ── single-model restore: "Animation Surface (GIF)" on a 2D Rectangle,
    # transient -- exercises the "elif is_2d:" loop (single fixed model,
    # one predict call per frame, no model-resolution overhead).
    with tempfile.TemporaryDirectory() as tmpdir:
        rect_geom = dde.geometry.Rectangle([0.0, 0.0], [1.0, 1.0])
        layers = [3, 16, 16, 1]
        model_path = _train_and_save_model(tmpdir, rect_geom, 0.0, 1.0, layers, "single_2d")
        cfg = _base_cfg(layers, "2D", False)
        script = win._build_restore_script(model_path, cfg, "adam", "Animation Surface (GIF)", 0, 3, tmpdir)
        check("_ta_model_for_t" not in script,
              "single-model Animation Surface (GIF) should never resolve a per-time-value TA model")
        proc = _run_script(script, tmpdir, "single_2d")
        check(proc.returncode == 0,
              f"single-model 2D Animation Surface (GIF) restore should run cleanly, got {proc.returncode}:\n"
              f"{proc.stdout}\n{proc.stderr}")
        check("RESTORE_DONE" in proc.stdout, "single-model 2D Animation Surface restore should finish")
        check(os.path.exists(os.path.join(tmpdir, "restored_animation.gif")),
              "single-model 2D Animation Surface restore should save restored_animation.gif")

    # ── single-model restore: "Animation Surface (GIF)" on a 3D Cuboid,
    # transient -- exercises the "if is_3d:" loop (geom.bbox read once,
    # same 6-flat-face approach as the static 3D Surface option).
    with tempfile.TemporaryDirectory() as tmpdir:
        cuboid_geom = dde.geometry.Cuboid([0.0, 0.0, 0.0], [1.0, 1.0, 1.0])
        layers = [4, 16, 16, 1]
        model_path = _train_and_save_model(tmpdir, cuboid_geom, 0.0, 1.0, layers, "single_3d")
        cfg = _base_cfg(layers, "3D", False)
        script = win._build_restore_script(model_path, cfg, "adam", "Animation Surface (GIF)", 0, 3, tmpdir)
        check("geom.bbox" in script, "single-model 3D Animation Surface (GIF) should read the bbox off the real geom")
        proc = _run_script(script, tmpdir, "single_3d")
        check(proc.returncode == 0,
              f"single-model 3D Animation Surface (GIF) restore should run cleanly, got {proc.returncode}:\n"
              f"{proc.stdout}\n{proc.stderr}")
        check("RESTORE_DONE" in proc.stdout, "single-model 3D Animation Surface restore should finish")
        check(os.path.exists(os.path.join(tmpdir, "restored_animation.gif")),
              "single-model 3D Animation Surface restore should save restored_animation.gif")

    # ── Time-Adaptive restore: "Animation Surface (GIF)" on a 2D
    # Rectangle, 2 steps -- confirms per-frame model routing
    # (_ta_model_for_t) and the geomtime-based bbox source both still
    # work through the shared helper's is_time_adaptive=True path.
    with tempfile.TemporaryDirectory() as tmpdir:
        rect_geom = dde.geometry.Rectangle([0.0, 0.0], [1.0, 1.0])
        layers = [3, 16, 16, 1]
        step0_path = _train_and_save_model(tmpdir, rect_geom, 0.0, 0.5, layers, "ta_step0")
        step1_path = _train_and_save_model(tmpdir, rect_geom, 0.5, 1.0, layers, "ta_step1")
        ta_steps = [
            {"t0": 0.0, "t1": 0.5, "model_path": step0_path,
             "cfg": {"layers": layers, "activation": "tanh", "loss_type": "MSE", "is_lbfgs": False}},
            {"t0": 0.5, "t1": 1.0, "model_path": step1_path,
             "cfg": {"layers": layers, "activation": "tanh", "loss_type": "MSE", "is_lbfgs": False}},
        ]
        cfg = {"layers": layers, "activation": "tanh", "x_min": 0.0, "x_max": 1.0,
               "y_min": 0.0, "y_max": 1.0, "problem_dim": "2D", "output_names": "u",
               "geometry_type": "Rectangle"}

        anim_script = win._build_restore_script_ta(ta_steps, cfg, "adam", "Animation Surface (GIF)", 0, 3, tmpdir)
        check("_ta_model_for_t" in anim_script,
              "TA Animation Surface (GIF) script should route each frame through _ta_model_for_t")
        check("_ta_build_geomtime" in anim_script,
              "TA Animation Surface (GIF) script should source its bbox from _ta_build_geomtime, not geom.bbox")
        proc = _run_script(anim_script, tmpdir, "ta_2d")
        check(proc.returncode == 0,
              f"TA 2D Animation Surface (GIF) restore should run cleanly, got {proc.returncode}:\n"
              f"{proc.stdout}\n{proc.stderr}")
        check("RESTORE_DONE" in proc.stdout, "TA 2D Animation Surface restore should finish")
        check("Restored step 1/2" in proc.stdout and "Restored step 2/2" in proc.stdout,
              "TA 2D Animation Surface restore should restore BOTH step models")
        check(os.path.exists(os.path.join(tmpdir, "restored_animation.gif")),
              "TA 2D Animation Surface restore should save restored_animation.gif")

    return failures


def main():
    failures = run()
    for f in failures:
        print("FAIL:", f)
    if failures:
        print(f"\n{len(failures)} FAILURE(S)")
        return 1
    print("\nALL ROUND 43 RESTORE ANIMATION-SURFACE REFACTOR TESTS PASSED")
    return 0


def test_round43_restore_anim_surface_refactor():
    failures = run()
    assert not failures, "\n".join(failures)


if __name__ == "__main__":
    sys.exit(main())
